# To represent the class we build a diagram

#A class is usually represented as a rectangular big box then at the top of that box, you write the name of the class e.g. ATM, then split the box into two equal partitions.

# Upper section will have data/variants/attributes e.g. pin, balance, etc

# Lower section will have all the name of methods e.g. menu, create pin, change pin, check balance, withdraw, etc

# Each thing will either have a bullet negative (-) sign or positive (+) sign 

# negative bullet means visible outside the class

